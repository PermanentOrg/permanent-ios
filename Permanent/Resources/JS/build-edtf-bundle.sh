#!/bin/bash
# Builds edtf-bundle.js and EDTFBundleSource.swift. Pin these to what Web's package-lock.json resolves.
set -euo pipefail
EDTF_VERSION=4.10.1
NEARLEY_VERSION=2.20.1
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${1:-$HERE/edtf-bundle.js}
SWIFT_OUT=${2:-$HERE/../../Common/Helpers/EDTFBundleSource.swift}

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://unpkg.com/edtf@${EDTF_VERSION}/dist/index.cjs"      -o "$work/edtf.cjs"
curl -fsSL "https://unpkg.com/nearley@${NEARLEY_VERSION}/lib/nearley.js" -o "$work/nearley.js"

{
  echo "/* Generated. edtf ${EDTF_VERSION} (BSD-2-Clause) + nearley ${NEARLEY_VERSION} (MIT)."
  echo "   Rebuild with Permanent/Resources/JS/build-edtf-bundle.sh. Do not edit by hand. */"
  echo 'var __m = {};'
  echo 'function __require(n){ if (__m[n]) return __m[n]; throw new Error("no module " + n); }'
  echo 'function __define(name, fn){ var module = { exports: {} }; var exports = module.exports; fn(module, exports, __require); __m[name] = module.exports; }'
  # The trailing echo after each cat is load-bearing: a dist file that ends in a
  # "//# sourceMappingURL" comment with no newline would comment out the next line.
  echo '__define("nearley", function(module, exports, require){'
  cat "$work/nearley.js"; echo
  echo '});'
  echo '__define("edtf", function(module, exports, require){'
  cat "$work/edtf.cjs"; echo
  echo '});'
  cat "$HERE/permanent-edtf.js"; echo
} > "$OUT"

# Inside #"""…"""# only these two sequences are not literal text.
if grep -qF '"""#' "$OUT" || grep -qF '\#' "$OUT"; then
  echo "edtf-bundle.js contains \"\"\"# or \\#, which would break the Swift raw string" >&2
  exit 1
fi

{
  echo '//'
  echo '//  EDTFBundleSource.swift'
  echo '//  Permanent'
  echo '//'
  echo '//  Created by Lucian Cerbu on 14.10.2026.'
  echo '//'
  echo ''
  echo '// Generated by Permanent/Resources/JS/build-edtf-bundle.sh from edtf-bundle.js. Do not edit by hand.'
  echo '// swiftlint:disable all'
  echo 'enum EDTFBundleSource {'
  echo '    static let javaScript = #"""'
  cat "$OUT"
  echo '"""#'
  echo '}'
  echo '// swiftlint:enable all'
} > "$SWIFT_OUT"

echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
echo "wrote $SWIFT_OUT ($(wc -c < "$SWIFT_OUT" | tr -d ' ') bytes)"
