#!/bin/sh
# Writes the zone-to-country table the time zone picker reads: one ISO country code per IANA zone, taken
# from the tz database's zone.tab on this Mac. Run it again after a tz database update, then rebuild.
set -eu
cd "$(dirname "$0")/.."

TABLE=/usr/share/zoneinfo/zone.tab
OUT=Permanent/Modules/EditMetadata/Models/TimeZoneCountryCodes.swift

{
  printf '//\n//  TimeZoneCountryCodes.swift\n//  Permanent\n//\n//  Created by Lucian Cerbu on 29.10.2026.\n//\n\n'
  printf '// Generated by Scripts/generate-timezone-country-codes.sh from the tz database'"'"'s zone.tab; do not edit by hand.\n\n'
  printf 'import Foundation\n\n'
  printf '/// One ISO country code per IANA zone, codes only; the country names are read from Foundation at run time.\n'
  printf 'enum TimeZoneCountryCodes {\n'
  printf '    static let codes: [String: String] = [\n'
  grep -v '^#' "$TABLE" | awk -F'\t' '$3 != "" { printf "        \"%s\": \"%s\",\n", $3, $1 }' | LC_ALL=C sort | sed '$ s/,$//'
  printf '    ]\n}\n'
} > "$OUT"

echo "wrote $(grep -c '": "' "$OUT") zones to $OUT"
